export function nivelDe(n) {
  const v = DATOS[Math.floor(Number(n)) - 1];
  if (!v) return null;
  const r = v % 20;
  return { palos: Math.floor(r / 5) + 1, dif: (r % 5) + 1, semilla: Math.floor(v / 20) };
}
