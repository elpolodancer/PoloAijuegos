// Se reparten en línea recta entre el tablero más fácil (3×3) y el más difícil (30×30): a más tamaño, más recompensa.
const entre = (n, minimo, maximo) => {
  const t = (Math.min(TAMANO_MAX, Math.max(TAMANO_MIN, n)) - TAMANO_MIN) / (TAMANO_MAX - TAMANO_MIN);
  return Math.round(minimo + (maximo - minimo) * t);
};
