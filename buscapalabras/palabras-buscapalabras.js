// Reglas: MAYÚSCULAS, solo letras A-Z (sin acentos ni Ñ), de 4 a 12 letras. Lo que no cumpla se descarta solo (y el bot lo avisa en «descartadas»).
// La etapa i del mapa usa el tema TEMAS[i % TEMAS.length]. CUIDADO: agregar, quitar o cambiar palabras CAMBIA los niveles ya generados
// (el bot compara una «huella»: si cambia, es que los niveles cambiaron). Para ampliar el banco sin tocar niveles viejos, hazlo antes de publicar.

export const descartadas = [];
const T = (nombre, icono, texto) => {
  const todas = texto.trim().split(/\s+/).map((w) => w.toUpperCase());
  const palabras = [];
  for (const w of todas) {
    if (!/^[A-Z]{4,12}$/.test(w)) { descartadas.push(nombre + ": " + w); continue; }
    if (!palabras.includes(w)) palabras.push(w);
  }
  return { nombre, icono, palabras };
};

