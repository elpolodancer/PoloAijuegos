// Esquinas -> lista de casillas [x, y] de la cola a la cabeza
function expandir(esq) {
  const out = [[esq[0][0], esq[0][1]]];
  for (let i = 1; i < esq.length; i++) {
    const [ax, ay] = esq[i - 1], [bx, by] = esq[i];
    const dx = Math.sign(bx - ax), dy = Math.sign(by - ay);
    for (let x = ax + dx, y = ay + dy; ; x += dx, y += dy) { out.push([x, y]); if (x === bx && y === by) break; }
  }
  return out;
}

// Devuelve { cols, filas, flechas: [{ celdas }] } del nivel fijo, o null si ese nivel no es fijo
export function nivelFijo(dif, nivel) {
  const n = FIJOS[dif] && FIJOS[dif][nivel - 1];
  return n ? { cols: n.cols, filas: n.filas, flechas: n.flechas.map((e) => ({ celdas: expandir(e) })) } : null;
}
